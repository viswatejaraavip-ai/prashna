def get_doc(doc: str, lang: str) -> Dict[str, str]:
    """{title, body_markdown, lang, doc} for ``doc`` in ``lang`` (falls back
    to English for unknown languages). Raises KeyError for unknown docs."""
    if doc not in DOCS:
        raise KeyError(doc)
    lang = lang if lang in LEGAL_LANGS else "en"
    body = BODIES[doc][lang].strip()
    for key, val in _vars().items():
        body = body.replace(key, val)
    return {"doc": doc, "lang": lang, "title": TITLES[doc][lang], "body_markdown": body}


def render_html(doc: str, lang: str) -> str:
    """Minimal HTML page for the public policy URLs (Play Console listing)."""
    import html
    import re
    d = get_doc(doc, lang)
    out = []
    in_list = False
    for line in d["body_markdown"].splitlines():
        text = html.escape(line.strip())
        text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
        if text.startswith("- "):
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append("<li>%s</li>" % text[2:])
            continue
        if in_list:
            out.append("</ul>")
            in_list = False
        if text.startswith("## "):
            out.append("<h2>%s</h2>" % text[3:])
        elif text:
            out.append("<p>%s</p>" % text)
    if in_list:
        out.append("</ul>")
    links = " · ".join('<a href="?lang=%s">%s</a>' % (code, name) for code, name in (
        ("en", "English"), ("hi", "हिन्दी"), ("te", "తెలుగు"), ("ta", "தமிழ்"),
        ("kn", "ಕನ್ನಡ"), ("ml", "മലയാളം")))
    return ("<!doctype html><html lang=\"%s\"><head><meta charset=\"utf-8\">"
            "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
            "<title>%s · Udhyath</title><style>body{font-family:system-ui,sans-serif;"
            "max-width:760px;margin:2rem auto;padding:0 16px;line-height:1.6;color:#222}"
            "h2{margin-top:1.6rem;font-size:1.15rem}nav{font-size:.9rem;margin-bottom:1rem}"
            "</style></head><body><nav>%s</nav><h1>%s</h1>%s</body></html>"
            % (d["lang"], html.escape(d["title"]), links, html.escape(d["title"]), "\n".join(out)))
