def bundle(lang: Optional[str]) -> Optional[Dict]:
    """English-term -> localized-term maps for one language, or None for en."""
    lang = (lang or "en").lower()
    if lang not in LANGUAGES or lang == "en":
        return None
    return {
        "language": lang,
        "planets": dict(zip(PLANETS, _PLANETS[lang])),
        "signs": dict(zip(SIGNS, _SIGNS[lang])),
        "nakshatras": dict(zip(NAKSHATRAS, _NAKSHATRAS[lang])),
        "weekdays": dict(zip(WEEKDAYS, _WEEKDAYS[lang])),
    }
